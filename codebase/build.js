#!/usr/bin/env node
/**
 * Builds the codebase map's generated indexes from the product repos.
 *
 *   node sis-brain/codebase/build.js            (from the workspace, or anywhere)
 *
 * Reads each repo in codebase/repos.json at its `ref` (the code of record, e.g.
 * origin/base-development) through git - never the working tree, never a checkout.
 * Writes codebase/generated/*.md, which is gitignored: every machine rebuilds it
 * after a fetch. Node only, no dependencies. Extracts structure only - paths,
 * names, routes, endpoints, tables - never config values or code bodies.
 *
 * How the map is used and kept is specified in the harness's skills/brain/SKILL.md.
 */
"use strict";

const fs = require("fs");
const path = require("path");
const cp = require("child_process");

const HERE = __dirname;
const WORKSPACE = path.resolve(HERE, "..", "..");
const OUT = path.join(HERE, "generated");

// ------------------------------------------------------------------ git access

function git(repoDir, args, input) {
  return cp.execFileSync("git", ["-C", repoDir, ...args], {
    input,
    maxBuffer: 1 << 30,
    stdio: ["pipe", "pipe", "ignore"],
  }).toString("utf8");
}

function listFiles(repoDir, ref) {
  return git(repoDir, ["ls-tree", "-r", "--name-only", ref]).split("\n").filter(Boolean);
}

/** Reads many files at `ref` in one `git cat-file --batch` call. */
function readFiles(repoDir, ref, paths) {
  const out = new Map();
  if (!paths.length) return out;
  const buf = cp.execFileSync("git", ["-C", repoDir, "cat-file", "--batch"], {
    input: paths.map((p) => `${ref}:${p}`).join("\n") + "\n",
    maxBuffer: 1 << 30,
  });
  let i = 0;
  for (const p of paths) {
    const nl = buf.indexOf(10, i);
    const header = buf.slice(i, nl).toString();
    i = nl + 1;
    if (/ missing$/.test(header)) continue;
    const size = Number(header.split(" ")[2]);
    out.set(p, buf.slice(i, i + size).toString("utf8"));
    i += size + 1;
  }
  return out;
}

const lineOf = (text, index) => text.slice(0, index).split("\n").length;
const cell = (s) => String(s == null || s === "" ? "—" : s).replace(/\|/g, "\\|").replace(/\s+/g, " ");

function table(headers, rows) {
  return [
    "| " + headers.join(" | ") + " |",
    "|" + headers.map(() => "---").join("|") + "|",
    ...rows.map((r) => "| " + r.map(cell).join(" | ") + " |"),
  ].join("\n");
}

function writeIndex(name, title, intro, headers, rows, stamp) {
  const body = [
    `# ${title}`,
    "",
    `Generated by \`codebase/build.js\` from ${stamp}. Do not edit: rebuilt after every fetch. ${rows.length} rows.`,
    intro ? "\n" + intro : "",
    "",
    table(headers, rows),
    "",
  ].join("\n");
  fs.writeFileSync(path.join(OUT, name), body);
  return rows.length;
}

// --------------------------------------------------------------- tiny TS parse

/** Skips a string or template literal starting at s[i]; returns the index after it. */
function skipString(s, i) {
  const q = s[i];
  for (i++; i < s.length; i++) {
    if (s[i] === "\\") i++;
    else if (s[i] === q) return i + 1;
  }
  return i;
}

/** Index of the bracket matching the one at s[i] ('[' or '{' or '('). */
function matchBracket(s, i) {
  let depth = 0;
  for (; i < s.length; i++) {
    const c = s[i];
    if (c === "'" || c === '"' || c === "`") { i = skipString(s, i) - 1; continue; }
    if (c === "/" && s[i + 1] === "/") { i = s.indexOf("\n", i); if (i < 0) return s.length; continue; }
    if (c === "/" && s[i + 1] === "*") { i = s.indexOf("*/", i) + 1; continue; }
    if (c === "[" || c === "{" || c === "(") depth++;
    else if (c === "]" || c === "}" || c === ")") { depth--; if (depth === 0) return i; }
  }
  return s.length;
}

/** Splits the top-level `{...}` elements of an array literal s[open..close]. */
function arrayObjects(s, open) {
  const close = matchBracket(s, open);
  const objs = [];
  for (let i = open + 1; i < close; i++) {
    const c = s[i];
    if (c === "'" || c === '"' || c === "`") { i = skipString(s, i) - 1; continue; }
    if (c === "/" && s[i + 1] === "/") { i = s.indexOf("\n", i); continue; }
    if (c === "{") { const end = matchBracket(s, i); objs.push(s.slice(i, end + 1)); i = end; }
    else if (c === "[" || c === "(") i = matchBracket(s, i);
  }
  return objs;
}

/** The object's own text with nested brackets blanked, so keys of children are not read. */
function ownText(obj) {
  let out = "";
  for (let i = 1; i < obj.length - 1; i++) {
    const c = obj[i];
    if (c === "'" || c === '"' || c === "`") { const e = skipString(obj, i); out += obj.slice(i, e); i = e - 1; continue; }
    if (c === "[" || c === "{") { const e = matchBracket(obj, i); out += c + "…"; i = e; continue; }
    out += c;
  }
  return out;
}

function parseRoutes(obj) {
  const own = ownText(obj);
  const str = (key) => { const m = own.match(new RegExp(`\\b${key}\\s*:\\s*['"\`]([^'"\`]*)['"\`]`)); return m ? m[1] : null; };
  const ident = (key) => { const m = own.match(new RegExp(`\\b${key}\\s*:\\s*([A-Za-z_$][\\w$]*)`)); return m ? m[1] : null; };
  const lc = own.match(/loadChildren\s*:[\s\S]*?import\(\s*['"`]([^'"`]+)['"`]\s*\)(?:[\s\S]*?\.then\(\s*\(?\s*\w+\s*\)?\s*=>\s*\w+\.(\w+))?/);
  const route = {
    path: str("path"),
    redirectTo: str("redirectTo"),
    component: ident("component"),
    loadChildren: lc ? lc[1] : null,
    children: [],
  };
  const ch = obj.search(/\bchildren\s*:\s*\[/);
  if (ch >= 0 && !lc) route.children = arrayObjects(obj, obj.indexOf("[", ch)).map(parseRoutes);
  return route;
}

// ------------------------------------------------------------------- Angular

function buildAngular(r, stamp) {
  const files = listFiles(r.dir, r.ref);
  const fileSet = new Set(files);
  const ts = files.filter((f) => f.endsWith(".ts") && !f.endsWith(".spec.ts"));
  const srcRoot = "src/";

  // tsconfig path aliases (baseUrl assumed src/, the Angular CLI default).
  let aliases = [];
  try {
    const tsconfig = readFiles(r.dir, r.ref, ["tsconfig.json"]).get("tsconfig.json") || "";
    const paths = tsconfig.match(/"paths"\s*:\s*\{([\s\S]*?)\}\s*\}/);
    if (paths) {
      for (const m of paths[1].matchAll(/"([^"]+)\/\*"\s*:\s*\[\s*"([^"]+)\/\*"/g)) aliases.push([m[1] + "/", m[2] + "/"]);
    }
  } catch { /* no tsconfig */ }

  function resolveImport(fromFile, spec) {
    let p = null;
    if (spec.startsWith(".")) p = path.posix.normalize(path.posix.join(path.posix.dirname(fromFile), spec));
    else if (spec.startsWith("app/")) p = srcRoot + spec;
    else for (const [a, t] of aliases) if (spec.startsWith(a)) { p = srcRoot + t + spec.slice(a.length); break; }
    if (!p) return null;
    for (const cand of [p, p + ".ts", p + "/index.ts"]) if (fileSet.has(cand)) return cand;
    return null;
  }

  const contents = readFiles(r.dir, r.ref, ts);
  const importsOf = (file) => {
    const map = new Map();
    const text = contents.get(file) || "";
    for (const m of text.matchAll(/import\s*\{([^}]+)\}\s*from\s*['"]([^'"]+)['"]/g)) {
      const target = resolveImport(file, m[2]);
      for (const name of m[1].split(",").map((x) => x.trim().split(/\s+as\s+/).pop()).filter(Boolean)) map.set(name, target);
    }
    return map;
  };

  // Component and class declarations, so any class name resolves to its file.
  const classFile = new Map();
  const components = [];
  for (const [file, text] of contents) {
    for (const m of text.matchAll(/export\s+(?:abstract\s+)?class\s+(\w+)/g)) if (!classFile.has(m[1])) classFile.set(m[1], file);
    const dec = text.match(/@Component\(\s*\{([\s\S]*?)\}\s*\)\s*export\s+class\s+(\w+)/);
    if (dec) {
      const sel = dec[1].match(/selector\s*:\s*['"`]([^'"`]+)['"`]/);
      components.push([sel ? sel[1] : null, dec[2], file]);
    }
  }

  // Routes: walk from the root routing file through every loadChildren.
  const routeRows = [];
  const seen = new Set();
  function routesIn(file) {
    const text = contents.get(file) || "";
    const arrays = [];
    const re = /(?:\w+\s*:\s*Routes?(?:\[\])?\s*=\s*|RouterModule\.for(?:Child|Root)\(\s*)\[/g;
    for (const m of text.matchAll(re)) arrays.push(m.index + m[0].length - 1);
    return arrays.flatMap((open) => arrayObjects(text, open).map(parseRoutes));
  }
  function moduleRouteFiles(moduleFile) {
    const list = [moduleFile];
    const text = contents.get(moduleFile) || "";
    for (const m of text.matchAll(/from\s*['"]([^'"]*rout[^'"]*)['"]/gi)) {
      const f = resolveImport(moduleFile, m[1]);
      if (f) list.push(f);
    }
    return list;
  }
  function walk(routes, prefix, file) {
    const imports = importsOf(file);
    for (const rt of routes) {
      if (rt.path == null) continue;
      const full = [prefix, rt.path].filter((x) => x !== "").join("/");
      if (rt.redirectTo != null) continue;
      if (rt.component) {
        const cf = imports.get(rt.component) || classFile.get(rt.component) || null;
        routeRows.push(["/" + full, rt.component, cf]);
      }
      if (rt.loadChildren) {
        const mod = resolveImport(file, rt.loadChildren) || resolveImport(file, rt.loadChildren + ".ts");
        if (mod && !seen.has(mod + "|" + full)) {
          seen.add(mod + "|" + full);
          for (const f of moduleRouteFiles(mod)) walk(routesIn(f), full, f);
        }
      }
      if (rt.children.length) walk(rt.children, full, file);
    }
  }
  const root = ["src/app/app.routing.ts", "src/app/app-routing.module.ts", "src/app/app.module.ts"].find((f) => contents.has(f));
  if (root) walk(routesIn(root), "", root);
  routeRows.sort((a, b) => a[0].localeCompare(b[0]));

  // API services: the `getContextPath()` convention, i.e. <apiBaseUrl>/<contextPath>/...
  const apiRows = [];
  for (const [file, text] of contents) {
    const m = text.match(/getContextPath\s*\(\s*\)\s*(?::\s*string\s*)?\{\s*return\s*['"`]([^'"`]+)['"`]/);
    if (!m) continue;
    const cls = text.match(/export\s+class\s+(\w+)/);
    apiRows.push([m[1], cls ? cls[1] : null, file]);
  }
  apiRows.sort((a, b) => a[0].localeCompare(b[0]));

  components.sort((a, b) => String(a[0]).localeCompare(String(b[0])));
  return { routeRows, apiRows, components };
}

// ---------------------------------------------------------------- Spring Boot

function buildSpring(r) {
  const files = listFiles(r.dir, r.ref);
  const java = files.filter((f) => f.startsWith("src/main/java/") && f.endsWith(".java"));

  // Endpoints: only files with a mapping annotation.
  const mapped = git(r.dir, ["grep", "-l", "-E", "@(Get|Post|Put|Delete|Patch|Request)Mapping", r.ref, "--", "src/main/java"])
    .split("\n").filter(Boolean).map((l) => l.slice(r.ref.length + 1));
  const mappedText = readFiles(r.dir, r.ref, mapped);
  const endpoints = [];
  const controllers = [];
  const mappingArg = (args) => {
    if (args == null) return [""];
    const m = args.match(/(?:value|path)\s*=\s*(\{[^}]*\}|"[^"]*")/) || args.match(/^\s*(\{[^}]*\}|"[^"]*")/);
    if (!m) return [""];
    const vals = [...m[1].matchAll(/"([^"]*)"/g)].map((x) => x[1]);
    return vals.length ? vals : [""];
  };
  for (const [file, text] of mappedText) {
    const cls = text.match(/(?:public\s+)?(?:abstract\s+)?class\s+(\w+)/);
    if (!cls) continue;
    const head = text.slice(0, cls.index);
    const clsMap = [...head.matchAll(/@RequestMapping\s*(?:\(([^)]*)\))?/g)].pop();
    const bases = clsMap ? mappingArg(clsMap[1]) : [""];
    let count = 0;
    const body = text.slice(cls.index);
    const offset = cls.index;
    const re = /@(Get|Post|Put|Delete|Patch|Request)Mapping\s*(?:\(([^)]*)\))?([\s\S]*?)\b(?:public|protected|private)?\s*[\w<>\[\],.? ]+\s+(\w+)\s*\(/g;
    for (const m of body.matchAll(re)) {
      let verb = m[1].toUpperCase();
      if (verb === "REQUEST") {
        const mm = (m[2] || "").match(/RequestMethod\.(\w+)/);
        verb = mm ? mm[1] : "ANY";
      }
      const before = body.slice(Math.max(0, m.index - 400), m.index);
      const grants = [...before.matchAll(/@PreAuthorizeGrant\(([^)]*)\)/g)].pop();
      const grant = grants ? grants[1].replace(/ModuleType\.|PermissionType\.|module\s*=\s*|permission\s*=\s*/g, "").replace(/\s+/g, " ").trim() : null;
      for (const base of bases) for (const sub of mappingArg(m[2])) {
        endpoints.push([verb, (base + sub).replace(/\/+/g, "/") || "/", `${cls[1]}#${m[4]}`, `${file}:${lineOf(text, offset + m.index)}`, grant]);
        count++;
      }
    }
    if (count && /@(Rest)?Controller/.test(head)) controllers.push([bases.join(", "), cls[1], file, count]);
  }
  endpoints.sort((a, b) => a[1].localeCompare(b[1]) || a[0].localeCompare(b[0]));
  controllers.sort((a, b) => a[0].localeCompare(b[0]));

  // Tables: @Table(name = "x") or @Table(name = Cls.TABLE) with TABLE = "x" in the same file.
  const entityFiles = git(r.dir, ["grep", "-l", "-E", "@Table\\(", r.ref, "--", "src/main/java"])
    .split("\n").filter(Boolean).map((l) => l.slice(r.ref.length + 1));
  const entityText = readFiles(r.dir, r.ref, entityFiles);
  // Names may be built from constants, e.g. TABLE = Globals.TABLE_PREFIX + "course".
  const globalConst = new Map();
  const constLines = git(r.dir, ["grep", "-h", "-E", 'static final String [A-Za-z_]+ *= *"[^"]*" *;', r.ref, "--", "src/main/java"]);
  for (const l of constLines.split("\n")) {
    const m = l.match(/static final String (\w+)\s*=\s*"([^"]*)"/);
    if (m && !globalConst.has(m[1])) globalConst.set(m[1], m[2]);
  }
  const evalConst = (expr, text, depth = 0) => expr.split("+").map((part) => {
    part = part.trim();
    const lit = part.match(/^"([^"]*)"$/);
    if (lit) return lit[1];
    const name = part.split(".").pop();
    const local = text.match(new RegExp(`\\b${name}\\s*=\\s*([^;]+);`));
    if (local && depth < 3) return evalConst(local[1], text, depth + 1);
    return globalConst.has(name) ? globalConst.get(name) : `{${part}}`;
  }).join("");
  const tables = [];
  for (const [file, text] of entityText) {
    const t = text.match(/@Table\(\s*name\s*=\s*([^,)]+)/);
    const cls = text.match(/class\s+(\w+)/);
    if (!t || !cls) continue;
    tables.push([evalConst(t[1], text), cls[1], file]);
  }
  tables.sort((a, b) => a[0].localeCompare(b[0]));

  // Outbound calls to other services.
  const clientFiles = git(r.dir, ["grep", "-l", "-E", "@FeignClient|RestTemplate|WebClient", r.ref, "--", "src/main/java"])
    .split("\n").filter(Boolean).map((l) => l.slice(r.ref.length + 1));
  const clients = [...readFiles(r.dir, r.ref, clientFiles)].map(([file, text]) => {
    const feign = text.match(/@FeignClient\(([^)]*)\)/);
    const kind = feign ? "Feign" : /WebClient/.test(text) ? "WebClient" : "RestTemplate";
    const target = feign ? (feign[1].match(/(?:name|value)\s*=\s*"([^"]+)"/) || [])[1] : null;
    const cls = text.match(/(?:class|interface)\s+(\w+)/);
    return [cls ? cls[1] : null, kind, target, file];
  });

  // Menus: navigation rows in Liquibase (translation key + route), labels from i18n/en.json.
  const menus = [];
  const navFiles = files.filter((f) => /^src\/main\/resources\/db\//.test(f) && /\.(xml|sql)$/.test(f));
  const navText = readFiles(r.dir, r.ref, navFiles);
  const byRoute = new Map();
  for (const f of [...navFiles].sort()) {
    const text = navText.get(f) || "";
    if (!text.includes("'navigation.")) continue;
    for (const stmt of text.split(/;|<\/sql>/)) {
      const key = stmt.match(/'(navigation\.[\w.]+)'/);
      const route = stmt.match(/'(\/[a-z][\w\-/]*)'/);
      if (key && route) byRoute.set(route[1], [key[1], f]);
    }
  }
  // Customer lines relabel screens (GCET calls "Course Master Catalogue" "Module"), so read every line's labels.
  const EN = "src/main/resources/i18n/en.json";
  const dicts = Object.entries(r.label_refs || { base: r.ref }).map(([line, ref]) => {
    let d = {};
    try { d = JSON.parse(readFiles(r.dir, ref, [EN]).get(EN) || "{}"); } catch { /* ref missing or unreadable */ }
    return [line, d];
  });
  const lookup = (dict, key, depth = 0) => {
    const v = key.split(".").reduce((o, k) => (o && typeof o === "object" ? o[k] : undefined), dict);
    if (typeof v !== "string") return null;
    return depth > 4 ? v : v.replace(/\{\{\s*([\w.]+)\s*\}\}/g, (_, k) => lookup(dict, k, depth + 1) || k);
  };
  const labelsOf = (key) => {
    const found = dicts.map(([line, d]) => [line, lookup(d, key)]).filter(([, l]) => l);
    const distinct = [...new Set(found.map(([, l]) => l))];
    if (distinct.length <= 1) return distinct[0] || null;
    return distinct.map((l) => `${l} (${found.filter(([, x]) => x === l).map(([line]) => line).join("/")})`).join("; ");
  };
  for (const [route, [key, f]] of byRoute) menus.push([labelsOf(key), key, route, f]);
  menus.sort((a, b) => a[2].localeCompare(b[2]));

  return { endpoints, controllers, tables, clients, menus, javaCount: java.length };
}

// ---------------------------------------------------------------------- main

function main() {
  const config = JSON.parse(fs.readFileSync(path.join(HERE, "repos.json"), "utf8"));
  fs.mkdirSync(OUT, { recursive: true });
  const results = {};
  const summary = [];
  const stamps = {};
  for (const r of config.repos) {
    r.dir = path.join(WORKSPACE, r.repo);
    if (!fs.existsSync(path.join(r.dir, ".git"))) { summary.push(`${r.repo}: skipped (not cloned in this workspace)`); continue; }
    let sha;
    try { sha = git(r.dir, ["rev-parse", "--short=10", r.ref]).trim(); }
    catch { summary.push(`${r.repo}: skipped (${r.ref} not found - run git fetch)`); continue; }
    const stamp = `\`${r.repo}\` at \`${r.ref}\` = \`${sha}\``;
    stamps[r.repo] = { ref: r.ref, commit: sha };
    const t0 = Date.now();
    if (r.kind === "angular") {
      const a = buildAngular(r, stamp);
      results[r.repo] = { kind: "angular", ...a };
      const n1 = writeIndex(`${r.repo}.routes.md`, `${r.repo} - routes`, "Full URL path (after the `#`) → routed component. Menu labels for these paths are in the backend's `menus` index.", ["Route", "Component", "File"], a.routeRows, stamp);
      const n2 = writeIndex(`${r.repo}.components.md`, `${r.repo} - components`, "Template tag → component class → file. Use it to find what a `<sis-…>` tag in a template is.", ["Selector", "Class", "File"], a.components, stamp);
      summary.push(`${r.repo} @ ${sha}: ${n1} routes, ${n2} components (${Date.now() - t0} ms)`);
    } else if (r.kind === "spring") {
      const s = buildSpring(r);
      results[r.repo] = { kind: "spring", ...s };
      const n1 = writeIndex(`${r.repo}.endpoints.md`, `${r.repo} - endpoints`, "HTTP verb and full path → controller method, with its `@PreAuthorizeGrant` module/permission.", ["Verb", "Path", "Handler", "File:line", "Grant"], s.endpoints, stamp);
      const n2 = writeIndex(`${r.repo}.tables.md`, `${r.repo} - tables`, "Database table → JPA entity. Liquibase changes live under `src/main/resources/db/changelog/`.", ["Table", "Entity", "File"], s.tables, stamp);
      const n3 = writeIndex(`${r.repo}.menus.md`, `${r.repo} - menus`, "Menu label (English) → translation key → frontend route, from the navigation rows in Liquibase. Last definition of a route wins. Labels come from `src/main/resources/i18n/en.json` on each line in `repos.json` `label_refs`; where lines differ, each label is followed by its lines.", ["Label", "Translation key", "Route", "Defined in"], s.menus, stamp);
      const n4 = writeIndex(`${r.repo}.clients.md`, `${r.repo} - outbound clients`, "Classes that call other services over HTTP.", ["Class", "Kind", "Target", "File"], s.clients, stamp);
      summary.push(`${r.repo} @ ${sha}: ${n1} endpoints, ${n2} tables, ${n3} menu routes, ${n4} clients (${Date.now() - t0} ms)`);
    }
  }

  // Cross-repo joins: screens (menu → route → component) and API (frontend service → controller).
  const angular = Object.entries(results).filter(([, v]) => v.kind === "angular");
  const spring = Object.entries(results).filter(([, v]) => v.kind === "spring");
  if (angular.length) {
    const menus = spring.flatMap(([repo, v]) => v.menus.map((m) => ({ repo, label: m[0], key: m[1], route: m[2] })));
    const menuByRoute = new Map(menus.map((m) => [m.route, m]));
    const screens = [];
    const apis = [];
    const controllers = spring.flatMap(([repo, v]) => v.controllers.map((c) => ({ repo, base: c[0], cls: c[1], file: c[2] })));
    for (const [repo, v] of angular) {
      for (const [route, comp, file] of v.routeRows) {
        const top = route.replace(/\/:[^/]+.*$/, "");
        const menu = menuByRoute.get(route) || menuByRoute.get(top);
        screens.push([menu ? menu.label : null, route, comp, `${repo}/${file || "?"}`]);
      }
      for (const [ctx, cls, file] of v.apiRows) {
        const want = "/api/v1/" + ctx.replace(/^\//, "");
        const hits = controllers.filter((c) => c.base.split(", ").some((b) => b === want || b === want.replace(/\/$/, "")));
        apis.push([ctx, cls, `${repo}/${file}`, hits.map((h) => `${h.repo}/${h.file}`).join(", ") || null]);
      }
    }
    const stampAll = Object.entries(stamps).map(([repo, s]) => `\`${repo}\` at \`${s.ref}\` = \`${s.commit}\``).join(", ");
    const n1 = writeIndex("screens.md", "Screens", "Start here when a ticket names a screen: menu label → route → routed component. Customer lines may label a screen differently - e.g. `Module (gcet)` - so search for the ticket's own word. A label is shown only where a menu row links that route (or its parent); screens reached only by buttons have none.", ["Menu label", "Route", "Component", "File"], screens, stampAll);
    const n2 = writeIndex("api.md", "Frontend API services → backend controllers", "Frontend service `getContextPath()` → the backend controller whose base path is `/api/v1/<contextPath>`. A service with no match calls another service or builds its URL differently.", ["Context path", "Frontend service", "Frontend file", "Backend controller"], apis, stampAll);
    summary.push(`joins: ${n1} screens, ${n2} API services`);
  }

  fs.writeFileSync(path.join(OUT, "stamp.json"), JSON.stringify({ built_at: new Date().toISOString(), repos: stamps }, null, 2) + "\n");
  console.log(OUT);
  for (const s of summary) console.log(s);
}

